/**
 * Strips redundant prefixes like "Traducción al español:" or "Translation into French:".
 */
export function cleanTranslationOutput(raw: string): string {
  if (!raw) return '';
  return raw
    .replace(/^(traducci[oó]n|tradução|traduction|übersetzung|перевод|traduzione|tłumaczenie|çeviri|bản dịch|terjemahan|translation|翻訳|번역|翻译)[\w\s\(\)]*[:：]\s*/i, '')
    .replace(/^["']|["']$/g, '')
    .trim();
}

/**
 * Returns authentic localized translation from dictionary if matched, or cleanly stripped fallback.
 */
export function lookupDictionaryTranslation(text: string, targetLanguage: string): string | null {
  if (!text) return null;
  const clean = text
    .toLowerCase()
    .replace(/[.,?!;:¡¿"']/g, '')
    .trim();

  const entry = COMMON_PHRASES_MAP[clean];
  if (entry) {
    return entry[targetLanguage] || entry['Spanish'] || null;
  }

  // Check partial key matches
  for (const [key, translations] of Object.entries(COMMON_PHRASES_MAP)) {
    if (clean === key || clean.startsWith(key) || key.startsWith(clean)) {
      if (translations[targetLanguage]) {
        return translations[targetLanguage];
      }
    }
  }

  return null;
}
