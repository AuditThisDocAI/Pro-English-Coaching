/**
 * Converts a user's saved phrases into dynamic flashcards.
 */
export function convertSavedPhrasesToFlashcards(savedPhrases: SavedPhrase[]): Flashcard[] {
  return savedPhrases.map((phrase) => {
    return {
      id: `saved_${phrase.id}`,
      deckId: 'saved-vault',
      category: phrase.mode ? phrase.mode.toUpperCase() : 'SAVED VAULT',
      frontContext: `Basic English • ${phrase.mode ? phrase.mode.toUpperCase() : 'EXPRESSION'}`,
      front: phrase.original,
      backProfessional: phrase.professional,
      backWhy: phrase.why || 'Clear, natural English expression for everyday conversation.',
      backTranslation: phrase.translation || '',
      backPractice: phrase.practice || 'Practice speaking this phrase aloud with friendly confidence.',
      mastery: 'new',
      isCustom: true,
      level: 'Beginner',
      tier: 'free',
      options: [
        { text: phrase.original, isCorrect: false, explanation: 'Casual or informal formulation.' },
        { text: phrase.professional, isCorrect: true, explanation: 'Natural everyday English phrasing.' },
      ],
    };
  });
}

/**
 * Helper to get a translation text for a given user native language.
 */
export function getFlashcardTranslation(
  card: Flashcard,
  nativeLanguage: NativeLanguage | string
): string {
  return getTranslationFromService(card, nativeLanguage);
}
