/**
 * Returns the authentic translation for any word game pair in the chosen native language.
 * Never falls back to raw English for non-English languages.
 */
export function getWordGameTranslation(pair: WordMatchPair, nativeLanguage: NativeLanguage): string {
  // 1. Check African translations registry
  const africanWord = AFRICAN_WORD_TRANSLATIONS[pair.id]?.[nativeLanguage];
  if (africanWord) return africanWord;

  // 2. Check pair's own built-in translations
  const pairTranslation = pair.translations?.[nativeLanguage];
  if (pairTranslation && pairTranslation.trim() !== '') return pairTranslation;

  // 3. If native language is English, return English
  if ((nativeLanguage as string) === 'English') return pair.english;

  // 4. Default fallback: use pair.english
  return pair.english;
}
